let currentLang = localStorage.getItem("recre-lang") || "fr";

function t(key) {
  return (translations[currentLang] && translations[currentLang][key]) || translations.fr[key] || key;
}

function difficultyLabel(levelKey) {
  const map = { facile: "levelEasyLabel", moyen: "levelMediumLabel", difficile: "levelHardLabel" };
  return t(map[levelKey] || levelKey);
}

function applyTranslations() {
  document.documentElement.lang = currentLang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });

  const flagEl = document.getElementById("lang-btn-flag");
  const codeEl = document.getElementById("lang-btn-code");
  if (flagEl) flagEl.textContent = currentLang === "fr" ? "🇫🇷" : "🇬🇧";
  if (codeEl) codeEl.textContent = currentLang.toUpperCase();

  document.querySelectorAll(".lang-option").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === currentLang);
  });

  if (typeof updateLoginBtn === "function") updateLoginBtn();

  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang: currentLang } }));
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem("recre-lang", lang);
  applyTranslations();
}

const langBtn = document.getElementById("lang-btn");
const langDropdown = document.getElementById("lang-dropdown");

if (langBtn && langDropdown) {
  langBtn.addEventListener("click", () => langDropdown.classList.toggle("show"));
  document.addEventListener("click", (e) => {
    if (!langBtn.contains(e.target) && !langDropdown.contains(e.target)) {
      langDropdown.classList.remove("show");
    }
  });
  document.querySelectorAll(".lang-option").forEach((btn) => {
    btn.addEventListener("click", () => {
      setLang(btn.dataset.lang);
      langDropdown.classList.remove("show");
    });
  });
}

applyTranslations();

